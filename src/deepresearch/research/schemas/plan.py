from enum import StrEnum
from uuid import UUID, uuid4

from pydantic import Field, model_validator

from deepresearch.research.schemas.common import SchemaBase


class ResearchPriority(StrEnum):
    """Priority assigned to a research task."""

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class ExpectedSourceType(StrEnum):
    """Types of sources the research should prioritize."""

    PRIMARY = "primary"
    ACADEMIC = "academic"
    OFFICIAL = "official"
    NEWS = "news"
    TECHNICAL = "technical"
    GENERAL = "general"


class ResearchSubQuestion(SchemaBase):
    """A specific question that contributes to the research objective."""

    id: UUID = Field(default_factory=uuid4)

    question: str = Field(
        min_length=5,
        max_length=1_000,
        description="A focused question that needs to be answered.",
    )


class ResearchSearchQuery(SchemaBase):
    """A search query associated with one or more research subquestions."""

    id: UUID = Field(default_factory=uuid4)

    query: str = Field(
        min_length=3,
        max_length=500,
        description="The search query to execute.",
    )

    sub_question_ids: list[UUID] = Field(
        min_length=1,
        max_length=12,
        description="Subquestions this search query is intended to support.",
    )


class ResearchPlan(SchemaBase):
    """Structured research plan generated by the planning stage."""

    objective: str = Field(
        min_length=10,
        max_length=2_000,
        description="The overall objective of the research.",
    )

    sub_questions: list[ResearchSubQuestion] = Field(
        min_length=1,
        max_length=12,
        description="Questions that collectively address the objective.",
    )

    search_queries: list[ResearchSearchQuery] = Field(
        min_length=1,
        max_length=20,
        description="Search queries required to investigate the subquestions.",
    )

    priority: ResearchPriority = ResearchPriority.MEDIUM

    expected_source_types: list[ExpectedSourceType] = Field(
        min_length=1,
        description="Source categories preferred for this research.",
    )

    @model_validator(mode="after")
    def validate_search_query_references(self) -> "ResearchPlan":
        """Ensure search queries reference existing subquestions."""

        sub_question_ids = {sub_question.id for sub_question in self.sub_questions}

        for search_query in self.search_queries:
            unknown_ids = set(search_query.sub_question_ids) - sub_question_ids

            if unknown_ids:
                raise ValueError(
                    "Search query references unknown subquestion IDs: "
                    f"{sorted(str(item) for item in unknown_ids)}"
                )

        return self

    @model_validator(mode="after")
    def validate_unique_identifiers(self) -> "ResearchPlan":
        """Prevent duplicate identifiers within the plan."""

        sub_question_ids = [item.id for item in self.sub_questions]

        search_query_ids = [item.id for item in self.search_queries]

        if len(sub_question_ids) != len(set(sub_question_ids)):
            raise ValueError("Subquestion IDs must be unique.")

        if len(search_query_ids) != len(set(search_query_ids)):
            raise ValueError("Search query IDs must be unique.")

        return self
